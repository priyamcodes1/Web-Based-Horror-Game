// Builds public/audio/manifest.json from the files in public/audio.
// Name files <sound>[_anything].<ext>, e.g. scream_01.ogg, scream-long.mp3, footstep_wood2.wav.
// Every file whose name starts with a known sound key replaces the built-in synthesized version
// (several files for one key = random variation). Runs automatically before `npm run build`.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'public', 'audio');
const KEYS = ['footstep', 'heavy_step', 'door_creak', 'door_slam', 'door_close', 'door_locked', 'unlock', 'drawer', 'pickup',
  'key_pickup', 'battery', 'flashlight', 'heal', 'inject', 'fuse_insert', 'power_down', 'power_up', 'thunder', 'heartbeat',
  'breath_in', 'breath_out', 'gasp', 'hurt', 'death_cry', 'whisper', 'wail', 'weep', 'scream', 'giggle', 'hum', 'growl',
  'roar', 'chain', 'cleaver', 'knock', 'whoosh', 'stinger', 'glass_break', 'wood_break', 'piano', 'musicbox', 'clock_chime',
  'car_door', 'car_start', 'crucifix', 'vanish', 'ui_hover', 'ui_click', 'rain', 'wind', 'drone', 'chase', 'menu', 'car', 'electric_hum'];
const EXT = /\.(ogg|mp3|wav|m4a|webm|opus|flac)$/i;

const man = { _readme: 'Generated by tools/audio-manifest.cjs from the files in this folder. Name files <sound>_<anything>.<ext>.' };
for (const k of KEYS) man[k] = [];
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => EXT.test(f)).sort() : [];
// longest key first so "door_close_1.ogg" doesn't match "door"
const byLen = [...KEYS].sort((a, b) => b.length - a.length);
let n = 0;
for (const f of files) {
  const base = f.toLowerCase();
  const k = byLen.find((key) => base === key + path.extname(base) || base.startsWith(key + '_') || base.startsWith(key + '-') || /\d/.test(base[key.length]) && base.startsWith(key));
  if (!k) { console.warn(`[audio] ${f}: name doesn't start with a known sound key - skipped`); continue; }
  man[k].push(f);
  n++;
}
fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(man, null, 1) + '\n');
console.log(`[audio] manifest: ${n} file(s) mapped`);
